#!/usr/bin/env python3
"""One-off provenance tool (not needed to rebuild the icon).

Outlines the word "Inkfall" in Fraunces SemiBold (wght 600, SIL OFL 1.1) and writes
design/wordmark_data.py, which build_icon.py embeds. Needs fontTools (+ brotli for woff2).

    python3 design/extract_wordmark.py /path/to/fraunces-latin-600-normal.woff2
"""
import os
import sys

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

TEXT = "Inkfall"
SIZE = 100.0       # em size of the stored outline
TRACKING = 1.0     # extra advance per letter, in the same units


def fmt(v):
    return f"{v:.2f}".rstrip("0").rstrip(".")


def main(font_path):
    tt = TTFont(font_path)
    if "fvar" in tt:
        loc = {a.axisTag: (600 if a.axisTag == "wght" else a.defaultValue) for a in tt["fvar"].axes}
        tt = instancer.instantiateVariableFont(tt, loc)
    gs, cmap, upm, hmtx = tt.getGlyphSet(), tt.getBestCmap(), tt["head"].unitsPerEm, tt["hmtx"]
    sc = SIZE / upm
    x, parts = 0.0, []
    for ch in TEXT:
        gn = cmap[ord(ch)]
        pen = SVGPathPen(gs, ntos=fmt)
        gs[gn].draw(TransformPen(pen, (sc, 0, 0, -sc, x, 0)))
        parts.append(pen.getCommands())
        x += hmtx[gn][0] * sc + TRACKING
    width = x - TRACKING
    os_2 = tt["OS/2"]
    cap = getattr(os_2, "sCapHeight", 0) * sc
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "wordmark_data.py")
    with open(out, "w") as fh:
        fh.write('"""Generated by extract_wordmark.py: "Inkfall" outlined in Fraunces SemiBold (SIL OFL 1.1).\n'
                 'Baseline y=0, y grows downward, em = 100 units."""\n')
        fh.write(f"WIDTH = {fmt(width)}\nCAP_HEIGHT = {fmt(cap)}\n")
        fh.write(f'PATH = "{" ".join(parts)}"\n')
    print("wrote", out, "width", fmt(width), "cap", fmt(cap))


if __name__ == "__main__":
    main(sys.argv[1])
